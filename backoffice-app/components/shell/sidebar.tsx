// Plain <a href> on purpose: the original is a multi-page site, and each page group here has its
// own root layout (own stylesheets), so every menu click is a full page load like before.
function MenuItems({ pathname }: { pathname: string | null }) {
  const t = useT();
  return (
    <ul className="navbar-nav" id="navbar-nav">
      {MENU.map((entry) => {
        if ("title" in entry) {
          return (
            <li key={entry.i18nKey} className="menu-title sideMenu">
              <span>{t(entry.i18nKey, entry.text)}</span>
            </li>
          );
        }
        const active = pathname !== null && (pathname === entry.href || (entry.match?.(pathname) ?? false));
        return (
          <li key={entry.screen} className={`nav-item sideMenu ${entry.screen} ${active ? "active" : ""}`}>
            <a href={entry.href} className={`nav-link ${active ? "active" : ""}`}>
              <img src={entry.icon} alt={entry.alt} draggable="false" />
              <span>{t(entry.i18nKey, entry.text)}</span>
            </a>
          </li>
        );
      })}
    </ul>
  );
}

function ActiveMenuItems() {
  return <MenuItems pathname={usePathname()} />;
}

